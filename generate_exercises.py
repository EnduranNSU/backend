def ex(id_: int, title: str, technique: str, muscles: str, limits: str,
       mistakes: str, alternatives: str, video_query: str, tags: list[str]) -> str:
    desc = "\n\n\n".join([
        title,
        "\n1. Техника выполнения упражнения\n\n" + technique.strip(),
        "\n2. Какие мышцы тренирует упражнение\n\n" + muscles.strip(),
        "\n3. Потенциальные ограничения и риски\n\n" + limits.strip(),
        "\n4. Типичные ошибки при выполнении\n\n" + mistakes.strip(),
        "\n5. Похожие и альтернативные упражнения\n\n" + alternatives.strip(),
    ])
    href = "https://www.youtube.com/results?search_query=" + video_query.replace(" ", "+")
    return json.dumps({
        "id": id_,
        "title": title,
        "description": desc,
        "video_href": href,
        "tags": tags,
    }, ensure_ascii=False)

