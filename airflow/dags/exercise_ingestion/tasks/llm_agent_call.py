def llm_agent_call(ex_name: str):
    conn = BaseHook.get_connection("yandex_opeani")
    extra = conn.extra_dejson

    api_key = extra["OPENAI_API_KEY"]

    client = OpenAI(
            api_key = api_key,
            base_url=extra["base_url"],
            project=extra["project"]
        )
    
    resp = client.chat.completions.create(
        model=f"gpt://{extra['project']}/{extra['base_model']}",
        messages=[
            {"role": "system", "content": SYSTEM_MESSAGE},
            {"role": "user", "content": ex_name}
        ],
        tools=[],
        temperature=0.1,
        max_tokens=7000,
    )

    print(f"Result of llm call for {ex_name}: \n{resp}")
    return resp.choices[0].message.content



